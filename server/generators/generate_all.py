from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from paths import DB_DIR
import generate_archive_detail_sql as archive_detail
import generate_card_detail_sql as card_detail
import generate_cheer_rankings as cheer_rankings
import generate_character_info_sql as character_info
import generate_custom_setting as custom_setting
import generate_daily_quest_stage_sql as daily_quest_stage
import generate_deck_sql as deck
import generate_dream_quest_stage_sql as dream_quest_stage
import generate_grade_quest_sql as grade_quest
import generate_grand_prix_sql as grand_prix
import generate_learning_stage_sql as learning_stage
import generate_music_mastery_sql as music_mastery
import generate_home_get_home as home
import generate_music_list as music_list
import generate_mission_get_list as mission_list
import generate_item_exchange_catalog as item_exchange_catalog
import generate_shop_get_list as shop_list
import generate_music_sql as music_db
import generate_quest_stage_sql as quest_stage
import generate_rhythm_game_sql as rhythm_game
import generate_rhythm_total_missions as rhythm_total_missions
import generate_sticker_list as sticker_list
import generate_user_items as item

TOOLS_DIR = Path(__file__).resolve().parent
SCHEMA_SQL = DB_DIR / "schema" / "001_init.sql"
SEED_SQL = DB_DIR / "seed" / "001_init.sql"

GENERATOR_NOTE = "-- Generated by server/generators/generate_all.py"


def main() -> None:
    print("=== Generate JSON (YAML -> JSON) ===")
    card_detail.generate_json()
    character_info.generate_json()
    custom_setting.generate_json()
    home.generate_json()
    mission_list.generate_json()
    rhythm_total_missions.generate_json()
    cheer_rankings.generate_json()
    item_exchange_catalog.generate_json()
    shop_list.generate_json()
    music_list.generate_json()
    sticker_list.generate_json()
    item.generate_json()

    archive_input = TOOLS_DIR / "data" / "archive_archive_details.json"
    if not archive_input.exists():
        # The SQL seed also carries archive details captured from the live
        # server (not part of MasterData, not in the repository).  Without
        # that capture only the JSON responses can be regenerated.
        print(f"=== Skip SQL: {archive_input.relative_to(TOOLS_DIR)} (captured archive data) is missing ===")
        return

    print("=== Generate SQL ===")
    schema_parts = [
        GENERATOR_NOTE,
        "PRAGMA foreign_keys = ON;",
        "",
        archive_detail.generate_schema_ddl(),
        "",
        card_detail.generate_schema_ddl(),
        "",
        character_info.generate_schema_ddl(),
        "",
        item.generate_schema_ddl(),
        "",
        deck.generate_schema_ddl(),
        "",
        rhythm_game.generate_schema_ddl(),
        "",
        quest_stage.generate_schema_ddl(),
        "",
        daily_quest_stage.generate_schema_ddl(),
        "",
        dream_quest_stage.generate_schema_ddl(),
        "",
        grade_quest.generate_schema_ddl(),
        "",
        grand_prix.generate_schema_ddl(),
        "",
        learning_stage.generate_schema_ddl(),
        "",
        music_mastery.generate_schema_ddl(),
        "",
        music_db.generate_schema_ddl(),
        "",
    ]
    SCHEMA_SQL.write_text("\n".join(schema_parts), encoding="utf-8", newline="\n")
    print(f"  Written: {SCHEMA_SQL}")

    seed_lines: list[str] = [
        GENERATOR_NOTE,
        "BEGIN IMMEDIATE;",
        *archive_detail.generate_seed_statements(),
        *card_detail.generate_seed_statements(),
        *character_info.generate_seed_statements(),
        *item.generate_seed_statements(),
        *deck.generate_seed_statements(),
        *rhythm_game.generate_seed_statements(),
        *quest_stage.generate_seed_statements(),
        *daily_quest_stage.generate_seed_statements(),
        *dream_quest_stage.generate_seed_statements(),
        *grade_quest.generate_seed_statements(),
        *grand_prix.generate_seed_statements(),
        *learning_stage.generate_seed_statements(),
        *music_mastery.generate_seed_statements(),
        *music_db.generate_seed_statements(),
        "COMMIT;",
        "",
    ]
    SEED_SQL.write_text("\n".join(seed_lines), encoding="utf-8", newline="\n")
    print(f"  Written: {SEED_SQL}")

    print("=== Done ===")


if __name__ == "__main__":
    main()
